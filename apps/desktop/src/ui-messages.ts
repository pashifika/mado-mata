import enData from './locales/ui.en.json' with {type: 'json'};
import jaData from './locales/ui.ja.json' with {type: 'json'};
import {interpolate} from './i18n-format.ts';
import type {PresetIssue, SchemaIssue, SourceMapIssue} from './metadata.ts';

function known(labels: Record<string, string>, value: string, key = value): string {
  return Object.hasOwn(labels, key) ? labels[key] : value;
}

function bounds(min: number | undefined, max: number | undefined) {
  return min === undefined ? max === undefined ? 'none' : 'maximum' : max === undefined ? 'minimum' : 'both';
}

function catalog(data: typeof enData) {
  return {
    recognition: {
      ...data.recognition,
      frame: (width: number, height: number) => interpolate(data.recognition.frame, {width, height}),
      limits: (input: number, inputPixels: string, crop: number, cropPixels: string) => interpolate(data.recognition.limits, {input, inputPixels, crop, cropPixels}),
      count: (count: number, limit: number) => interpolate(data.recognition.count, {count, limit}),
      undoHelp: (count: number, limit: number) => interpolate(data.recognition.undoHelp, {count, limit}),
      trialFor: (name: string) => interpolate(data.recognition.trialFor, {name}),
      cropFor: (name: string) => interpolate(data.recognition.cropFor, {name}),
      savedFacts: (asset: string, width: number, height: number) => interpolate(data.recognition.savedFacts, {asset, width, height}),
      threshold: (value: string, max: number) => interpolate(data.recognition.threshold, {value, max}),
      bytes: (count: number, limit: number) => interpolate(data.recognition.bytes, {count, limit}),
      issue: (code: keyof typeof data.recognition.issues) => data.recognition.issues[code],
      notice: (code: keyof typeof data.recognition.notices) => data.recognition.notices[code],
      block: (code: keyof typeof data.recognition.blocks) => data.recognition.blocks[code],
      engineLimit: (count: number) => interpolate(data.recognition.engineLimit, {count}),
      selection: (count: number, limit: number | null) => interpolate(data.recognition.selection[limit === null ? 'unknown' : 'known'], {count, limit: limit ?? ''}),
      freshness: (value: keyof typeof data.recognition.freshnessLabels) => data.recognition.freshnessLabels[value],
      freshnessHelp: (value: keyof typeof data.recognition.freshnessHelps) => data.recognition.freshnessHelps[value],
      regions: (count: number) => interpolate(data.recognition.regions[count === 1 ? 'one' : 'other'], {count}),
      rect: (x: number, y: number, width: number, height: number) => interpolate(data.recognition.rect, {x, y, width, height}),
      templateThreshold: (value: string) => interpolate(data.recognition.templateThreshold, {value}),
      score: (value: string) => interpolate(data.recognition.score, {value}),
      cleanupState: (reaped: boolean, forced: boolean) => data.recognition.cleanupStates[!reaped ? 'unreported' : forced ? 'forced' : 'reaped'],
      crops: (count: number) => interpolate(data.recognition.crops[count === 1 ? 'one' : 'other'], {count}),
      basis: (frameWidth: number, frameHeight: number, x: number, y: number, width: number, height: number) => interpolate(data.recognition.basis, {frameWidth, frameHeight, x, y, width, height}),
      defaultName: (number: number) => interpolate(data.recognition.defaultName, {number}),
      percent: (value: number) => interpolate(data.recognition.percent, {value}),
      scale: (width: number, height: number, percent: number) => interpolate(data.recognition.scale, {width, height, percent}),
      searchLabel: (name: string) => interpolate(data.recognition.searchLabel, {name}),
    },
    phase: (value: string) => known(data.phase, value),
    operation: (value: string) => known(data.operation, value),
    lane: (value: string) => known(data.lane, value),
    severity: (value: string) => known(data.severity, value, value.toLowerCase()),
    entryOutcome: (value: string) => known(data.entryOutcome, value),
    common: {
      ...data.common,
      revision: (label: string, revision: number) => interpolate(data.common.revision, {label, revision}),
    },
    settings: {
      ...data.settings,
      invalid: (count: number, categories: string) => interpolate(data.settings.invalid[categories ? count === 1 ? 'oneCategories' : 'otherCategories' : count === 1 ? 'one' : 'other'], {count, categories}),
      invalidCount: (count: number) => interpolate(data.settings.invalidCount, {count}),
      wait: (reason: string) => interpolate(data.settings.wait, {reason}),
      cards: (count: number) => interpolate(data.settings.cards[count === 1 ? 'one' : 'other'], {count}),
      seconds: (count: number) => interpolate(data.settings.seconds[count === 1 ? 'one' : 'other'], {count}),
      logLimitHelp: (limit: number | null) => interpolate(data.settings.logLimitHelp, {limit: limit ?? data.common.notLoaded}),
    },
    environment: {
      ...data.environment,
      truncated: (count: number) => interpolate(data.environment.truncated[count === 1 ? 'one' : 'other'], {count}),
      staleHelp: (reasons: string[]) => interpolate(data.environment.staleHelp, {reasons: reasons.join(data.environment.reasonSeparator)}),
      wait: (reason: string) => interpolate(data.environment.wait, {reason}),
      unsupported: (profile: string) => interpolate(data.environment.unsupported, {profile}),
      profileLabel: (profile: keyof typeof data.environment.profileLabels) => data.environment.profileLabels[profile],
      mismatch: (model: string, language: string, provider: string, runtime: string) => interpolate(data.environment.mismatch, {model, language, provider, runtime}),
    },
    run: {
      ...data.run,
      heading: (label: string) => interpolate(data.run.heading, {label}),
      owned: (operation: string | null) => interpolate(data.run.owned, {operation: operation ?? data.common.none}),
      settled: (operation: string | null) => interpolate(data.run.settled, {operation: operation ?? data.common.none}),
      inspected: (revision: number) => interpolate(data.run.inspected, {revision}),
      descriptorHelp: (limit: number) => interpolate(data.run.descriptorHelp, {limit}),
      startUses: (profile: string | null, replay: boolean, environment: string | null, descriptor: string | null) => interpolate(data.run.startUses[replay ? profile === null ? 'replayDraft' : 'replayProfile' : profile === null ? 'draft' : 'profile'], {profile: profile ?? '', environment: environment ?? data.run.noSavedEnvironment, descriptor: descriptor ?? data.common.none}),
      olderRevision: (old: number, current: number) => interpolate(data.run.olderRevision, {old, current}),
      stopTarget: (operation: string | null) => interpolate(data.run.stopTarget, {operation: operation ?? data.common.none}),
      runKind: (lane: string) => interpolate(data.run.runKind, {lane}),
    },
    target: {
      ...data.target,
      argument: (number: number) => interpolate(data.target.argument, {number}),
      revision: (revision: number) => interpolate(data.target.revision, {revision}),
    },
    result: {
      ...data.result,
      truncated: (count: number) => interpolate(data.result.truncated[count === 1 ? 'one' : 'other'], {count}),
      disclosureHelp: (privateDetail: boolean, kib: number) => interpolate(data.result.disclosureHelp[privateDetail ? 'private' : 'ordinary'], {kib}),
    },
    schema: {
      ...data.schema,
      fieldAction: (present: boolean, path: string) => interpolate(data.schema.fieldAction[present ? 'omit' : 'add'], {path}),
      omittedDefault: (value: string) => interpolate(data.schema.omittedDefault, {value}),
      unknown: (path: string, value: string) => interpolate(data.schema.unknown, {path, value}),
      ordered: (count: number, min: number | undefined, max: number | undefined) => interpolate(data.schema.ordered[bounds(min, max)][count === 1 ? 'one' : 'other'], {count, min: min ?? '', max: max ?? ''}),
      moveUp: (path: string) => interpolate(data.schema.moveUp, {path}),
      moveDown: (path: string) => interpolate(data.schema.moveDown, {path}),
      removeItem: (path: string) => interpolate(data.schema.removeItem, {path}),
      invalid: (value: string) => interpolate(data.schema.invalid, {value}),
      length: (min: number, max: number | undefined) => interpolate(data.schema.length[max === undefined ? 'unbounded' : 'bounded'], {min, max: max ?? ''}),
      numeric: (type: string, min: number | undefined, max: number | undefined) => interpolate(data.schema.numeric[bounds(min, max)], {type, min: min ?? '', max: max ?? ''}),
      mismatch: (type: string, value: string) => interpolate(data.schema.mismatch, {type, value}),
      replace: (type: string) => interpolate(data.schema.replace, {type}),
    },
    logs: {
      ...data.logs,
      missing: (sequence: number) => interpolate(data.logs.missing, {sequence}),
      filtered: (count: number) => interpolate(data.logs.filtered[count === 1 ? 'one' : 'other'], {count}),
      stats: (shown: number, scoped: number, retained: number, limit: number) => interpolate(data.logs.stats, {shown, scoped, retained, limit}),
      fileError: (error: string) => interpolate(data.logs.fileError, {error}),
      lossHelp: (loss: boolean) => data.logs.lossHelp[loss ? 'loss' : 'none'],
    },
    notifications: {
      ...data.notifications,
      dismiss: (id: number) => interpolate(data.notifications.dismiss, {id}),
      event: (id: number) => interpolate(data.notifications.event, {id}),
    },
    workspaces: {
      ...data.workspaces,
      attention: (count: number) => interpolate(data.workspaces.attention[count === 1 ? 'one' : 'other'], {count}),
      label: (name: string) => interpolate(data.workspaces.label, {name}),
      open: (count: number) => interpolate(data.workspaces.open, {count}),
      closeLabel: (name: string) => interpolate(data.workspaces.closeLabel, {name}),
      closeTitle: (name: string) => interpolate(data.workspaces.closeTitle, {name}),
    },
    bootstrap: {
      ...data.bootstrap,
      state: (value: string) => known(data.bootstrap.state, value),
      legacyHelp: (path: string) => interpolate(data.bootstrap.legacyHelp, {path}),
      block: (kind: keyof typeof data.bootstrap.block) => data.bootstrap.block[kind],
    },
    create: {
      ...data.create,
      count: (count: number, limit: number) => interpolate(data.create.count, {count, limit}),
      openLimit: (limit: number) => interpolate(data.create.openLimit, {limit}),
      savedLimit: (limit: number) => interpolate(data.create.savedLimit, {limit}),
      errors: (kind: keyof typeof data.create.errors) => data.create.errors[kind],
    },
    reopen: {
      ...data.reopen,
      directory: (id: string) => interpolate(data.reopen.directory, {id}),
      archive: (id: string) => interpolate(data.reopen.archive, {id}),
      references: (count: number) => interpolate(data.reopen.references, {count}),
      saved: (count: number, limit: number) => interpolate(data.reopen.saved, {count, limit}),
      limit: (limit: number) => interpolate(data.reopen.limit, {limit}),
      reopenLabel: (name: string) => interpolate(data.reopen.reopenLabel, {name}),
    },
    recovery: {
      ...data.recovery,
      outcomeStatus: (value: string) => known(data.recovery.outcomeStatus, value),
      confirmReset: (name: string, id: string, owner: string, packageId: string) => interpolate(data.recovery.confirmReset, {name, id, owner, package: packageId}),
    },
    guidance: {
      ...data.guidance,
      scope: (label: string) => interpolate(data.guidance.scope, {label}),
    },
    authoring: {
      ...data.authoring,
      scope: (label: string) => interpolate(data.authoring.scope, {label}),
      kind: (value: string) => known(data.authoring.kinds, value),
      unsavedFiles: (count: number) => interpolate(data.authoring.unsavedFiles[count === 1 ? 'one' : 'other'], {count}),
      binary: (bytes: number) => interpolate(data.authoring.binary, {bytes}),
      editorLabel: (path: string) => interpolate(data.authoring.editorLabel, {path}),
      position: (line: number, column: number) => interpolate(data.authoring.position, {line, column}),
      lines: (count: number) => interpolate(data.authoring.lines[count === 1 ? 'one' : 'other'], {count}),
      matches: (count: number, current: number | null, capped: boolean) => interpolate(data.authoring.matches[count === 0 ? 'none' : capped ? 'capped' : current === null ? 'count' : 'position'], {count, current: current ?? ''}),
      valid: (revision: string) => interpolate(data.authoring.valid, {revision}),
      invalid: (revision: string, count: number) => interpolate(data.authoring.invalid[count === 1 ? 'one' : 'other'], {revision, count}),
      staleValidation: (revision: string) => interpolate(data.authoring.staleValidation, {revision}),
      location: (path: string, line: number, column: number) => interpolate(data.authoring.location, {path, line, column}),
      goTo: (location: string) => interpolate(data.authoring.goTo, {location}),
      renameHeading: (path: string) => interpolate(data.authoring.renameHeading, {path}),
      fileActions: (path: string) => interpolate(data.authoring.fileActions, {path}),
      confirmRemove: (path: string) => interpolate(data.authoring.confirmRemove, {path}),
      block: (kind: keyof typeof data.authoring.block) => data.authoring.block[kind],
      blockedOther: (owner: string) => interpolate(data.authoring.blockedOther, {owner}),
      startBlocked: (owner: string) => interpolate(data.authoring.startBlocked, {owner}),
      stripKind: (packageId: string) => interpolate(data.authoring.stripKind, {package: packageId}),
      dirtyHeading: (intent: keyof typeof data.authoring.dirtyHeading) => data.authoring.dirtyHeading[intent],
      presetLabel: (id: string) => interpolate(data.authoring.presetLabel, {id}),
      sourceMapLabel: (module: string) => interpolate(data.authoring.sourceMapLabel, {module}),
      jsonLocation: (problem: string, line: number, column: number) => interpolate(data.authoring.jsonLocation, {problem: known(data.authoring.jsonProblems, problem), line, column}),
      normalizedNumbers: (numbers: string) => interpolate(data.authoring.normalizedNumbers, {numbers}),
      normalizedDuplicates: (paths: string) => interpolate(data.authoring.normalizedDuplicates, {paths}),
      runtimeLabel: (runtime: string) => known(data.authoring.runtimes, runtime),
      runtimeUnsupported: (runtime: string) => interpolate(data.authoring.runtimeUnsupported, {runtime}),
      entryName: (name: string) => known(data.authoring.entryNames, name),
      entryModule: (entry: string) => interpolate(data.authoring.entryModule, {entry}),
      entryFunction: (entry: string) => interpolate(data.authoring.entryFunction, {entry}),
      moduleUndeclared: (path: string) => interpolate(data.authoring.moduleUndeclared, {path}),
      helper: (name: string, version: string) => interpolate(data.authoring.helper, {name, version}),
      assetDimensions: (width: string, height: string) => interpolate(data.authoring.assetDimensions, {width, height}),
      addFieldHeading: (path: string) => interpolate(data.authoring.addFieldHeading, {path}),
      schemaType: (type: string) => known(data.authoring.schemaTypes, type),
      unsupportedType: (type: string) => interpolate(data.authoring.unsupportedType, {type}),
      boundLabel: (key: string) => known(data.authoring.bounds, key),
      enumValue: (index: number) => interpolate(data.authoring.enumValue, {index}),
      enumRemove: (index: number) => interpolate(data.authoring.enumRemove, {index}),
      nestedDefault: (value: string) => interpolate(data.authoring.nestedDefault, {value}),
      schemaProblems: (count: number) => interpolate(data.authoring.schemaProblems[count === 1 ? 'one' : 'other'], {count}),
      schemaIssue: (issue: SchemaIssue) => interpolate(data.authoring.schemaIssue[issue.code], {key: 'key' in issue ? issue.key : ''}),
      schemaRepair: (issue: SchemaIssue) => interpolate(data.authoring.schemaRepair[issue.code], {key: 'key' in issue ? issue.key : ''}),
      presetIssue: (issue: PresetIssue) => interpolate(data.authoring.presetIssue[issue.code], {key: 'key' in issue ? issue.key : ''}),
      presetRepair: (issue: PresetIssue) => interpolate(data.authoring.presetRepair[issue.code], {key: 'key' in issue ? issue.key : ''}),
      characters: (count: number) => interpolate(data.authoring.characters[count === 1 ? 'one' : 'other'], {count}),
      sourceMapIssue: (issue: SourceMapIssue) => interpolate(data.authoring.sourceMapIssue[issue.code], {index: 'index' in issue ? issue.index + 1 : ''}),
    },
  };
}

const en = catalog(enData);
const ja: typeof en = catalog(jaData);
export const uiMessages = {en, ja};
